import {
  CatalogValidationError,
  normalizeCatalogOptions,
  type CatalogCategory,
  type CatalogOptions,
  type ModalityNature,
} from "./catalog-options";

/** Draft operations never change an existing identity. */
export function renameCatalogOption(catalog: CatalogOptions, category: CatalogCategory, id: string, label: string): CatalogOptions {
  return { ...catalog, [category]: catalog[category].map((option) => option.id === id ? { ...option, label } : option) };
}

export function setCatalogOptionActive(catalog: CatalogOptions, category: CatalogCategory, id: string, active: boolean): CatalogOptions {
  return { ...catalog, [category]: catalog[category].map((option) => option.id === id ? { ...option, active } : option) };
}

export function setCatalogModalityNature(catalog: CatalogOptions, id: string, nature: ModalityNature): CatalogOptions {
  return { ...catalog, modalities: catalog.modalities.map((option) => option.id === id ? { ...option, nature } : option) };
}

export function moveCatalogOption(catalog: CatalogOptions, category: CatalogCategory, id: string, direction: -1 | 1): CatalogOptions {
  const options = catalog[category].filter((option) => option.active);
  const inactive = catalog[category].filter((option) => !option.active);
  const index = options.findIndex((option) => option.id === id);
  const target = index + direction;
  const option = options[index];
  const neighbor = options[target];
  if (index < 0 || !option || !neighbor) return catalog;
  options[index] = neighbor;
  options[target] = option;
  return { ...catalog, [category]: [...options, ...inactive].map((entry, position) => ({ ...entry, order: position + 1 })) };
}

/** Only a completed historical-use check may authorize physical removal. */
export function removeCatalogOption(catalog: CatalogOptions, category: CatalogCategory, id: string, used: boolean): CatalogOptions {
  if (!catalog[category].some((option) => option.id === id)) throw new Error("Catalog option not found");
  if (used) return setCatalogOptionActive(catalog, category, id, false);
  return { ...catalog, [category]: catalog[category].filter((option) => option.id !== id) };
}

/** Restoration changes the existing entry, never appends a second identity. */
export function restoreCatalogOption(catalog: CatalogOptions, category: CatalogCategory, id: string): CatalogOptions {
  if (!catalog[category].some((option) => option.id === id)) throw new Error("Catalog option not found");
  return setCatalogOptionActive(catalog, category, id, true);
}

/** IDs are generated by the caller once; labels never participate in identity. */
export function addCatalogOption(catalog: CatalogOptions, category: CatalogCategory, id: string, label: string, nature?: ModalityNature): CatalogOptions {
  if (catalog[category].some((option) => option.id === id)) {
    throw new CatalogValidationError([{ path: `${category}.id`, code: "duplicate_id" }]);
  }
  const added = {
    id, label: label.trim(), active: true,
    order: Math.max(0, ...catalog[category].map((option) => option.order)) + 1,
    ...(category === "modalities" ? { nature } : {}),
  };
  // Validate only the addition: an unfinished rename elsewhere remains a draft.
  normalizeCatalogOptions({ [category]: [added] });
  return { ...catalog, [category]: [...catalog[category], added] } as CatalogOptions;
}

/** Every save includes all three groups, including unchanged Bloom defaults. */
export function prepareCatalogForSave(catalog: CatalogOptions): CatalogOptions {
  return normalizeCatalogOptions(catalog);
}