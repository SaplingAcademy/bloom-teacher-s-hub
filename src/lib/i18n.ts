/**
 * Resolves a translation key (e.g., 'common.save' or 'nav.students')
 */
export function t(key: string, lang: Language = "pt", fallback?: string): string {
  const parts = key.split(".");
  let current: any = translations[lang] || translations["pt"];

  for (const part of parts) {
    if (current && typeof current === "object" && part in current) {
      current = current[part];
    } else {
      current = null;
      break;
    }
  }

  if (typeof current === "string") {
    return current;
  }

  // Fallback to Portuguese dictionary if key missing in English
  if (lang !== "pt") {
    let ptCurrent: any = translations["pt"];
    for (const part of parts) {
      if (ptCurrent && typeof ptCurrent === "object" && part in ptCurrent) {
        ptCurrent = ptCurrent[part];
      } else {
        ptCurrent = null;
        break;
      }
    }
    if (typeof ptCurrent === "string") {
      return ptCurrent;
    }
  }

  return fallback || key;
}

/**
 * Localizes database status and enum strings cleanly
 */
export function formatStatusLabel(statusKey: string | undefined | null, lang: Language = "pt"): string {
  if (!statusKey) return "";
  const normalized = String(statusKey).toLowerCase().trim();
  const localized = t(`status.${normalized}`, lang, "");
  if (localized && localized !== `status.${normalized}`) {
    return localized;
  }
  // Return capitalize original if not found in dictionary
  return normalized.charAt(0).toUpperCase() + normalized.slice(1);
}

/**
 * Localizes weekday names cleanly
 */
export function formatWeekdayName(dayStr: string | undefined | null, lang: Language = "pt", short: boolean = false): string {
  if (!dayStr) return "";
  const cleanDay = String(dayStr).trim();
  const lookupKey = short ? cleanDay.substring(0, 3) : cleanDay;
  const localized = t(`weekdays.${cleanDay}`, lang, "");
  if (localized && localized !== `weekdays.${cleanDay}`) {
    return short ? t(`weekdays.${cleanDay.substring(0, 3)}`, lang, localized.substring(0, 3)) : localized;
  }
  return cleanDay;
}
